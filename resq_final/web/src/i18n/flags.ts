const TABLES: Partial<Record<Lang, Table>> = { hi, bn, as };

export function flagText(flag: Flag, lang: Lang): { label: string; detail: string } {
  const table = TABLES[lang];
  const pair = table?.[flag.code];
  if (!pair) return { label: flag.label || flag.code, detail: flag.detail || "" };
  const n = /(\d+)/.exec(flag.label || "")?.[1] ?? /(\d+)/.exec(flag.detail || "")?.[1] ?? "";
  const id = /#(\S+?)(?=[\s,.)]|$)/.exec(flag.detail || "")?.[1] ?? "";
  const fill = (s: string) => s.replace("{n}", n).replace("{id}", id);
  return { label: fill(pair[0]), detail: fill(pair[1]) };
}
